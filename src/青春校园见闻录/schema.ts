// 青春校园见闻录 — MVU 变量结构（Zod 4）
// 依据：创作规划.yaml → mvu 段 + 主代理定案
//   · 日期为世界内自由格式字符串（如「4月7日」，星期可含可不含，非现实年份）
//   · 时间约定 24 小时制「HH:MM」，仅作书写约定、不做硬校验（避免格式偏差导致整次更新被丢弃）
//   · 时段为封闭枚举（早晨/上午/午休/放学/傍晚/夜晚）
//   · 不设好感度/关系阶段等数值型关系变量；不追踪 <user>

export const Schema = z
  .object({
    系统: z
      .object({
        日期: z.string().prefault('4月7日'), // 世界内日期，自由格式
        时间: z.string().prefault('08:00'), // 约定「HH:MM」24 小时制
        时段: z.enum(['早晨', '上午', '午休', '放学', '傍晚', '夜晚']).prefault('早晨'),
        地点: z.string().prefault('青叶丘高等学校'), // 自由文本，与地理条目关键词呼应
      })
      .prefault({}),
    // 角色段（琴音/遥/栞 同构）：身体为部位拆分结构（四部位固定必需键）
    //   胸部=罩杯、形状与当前状态；腰身=腰臀线条与触感焦点；小穴/后庭=当前状态（肛塞佩戴时记于后庭）
    //   当前穿着含裸露状态与配饰组合
    琴音: z
      .object({
        当前穿着: z.string().prefault('待初始化'),
        所在: z.string().prefault('待初始化'),
        身体: z
          .record(z.enum(['胸部', '腰身', '小穴', '后庭']), z.string())
          .prefault({ 胸部: '待初始化', 腰身: '待初始化', 小穴: '待初始化', 后庭: '待初始化' }),
      })
      .prefault({
        当前穿着: '待初始化',
        所在: '待初始化',
        身体: { 胸部: '待初始化', 腰身: '待初始化', 小穴: '待初始化', 后庭: '待初始化' },
      }),
    遥: z
      .object({
        当前穿着: z.string().prefault('待初始化'),
        所在: z.string().prefault('待初始化'),
        身体: z
          .record(z.enum(['胸部', '腰身', '小穴', '后庭']), z.string())
          .prefault({ 胸部: '待初始化', 腰身: '待初始化', 小穴: '待初始化', 后庭: '待初始化' }),
      })
      .prefault({
        当前穿着: '待初始化',
        所在: '待初始化',
        身体: { 胸部: '待初始化', 腰身: '待初始化', 小穴: '待初始化', 后庭: '待初始化' },
      }),
    栞: z
      .object({
        当前穿着: z.string().prefault('待初始化'),
        所在: z.string().prefault('待初始化'),
        身体: z
          .record(z.enum(['胸部', '腰身', '小穴', '后庭']), z.string())
          .prefault({ 胸部: '待初始化', 腰身: '待初始化', 小穴: '待初始化', 后庭: '待初始化' }),
      })
      .prefault({
        当前穿着: '待初始化',
        所在: '待初始化',
        身体: { 胸部: '待初始化', 腰身: '待初始化', 小穴: '待初始化', 后庭: '待初始化' },
      }),
  })
  .prefault({});

export type Schema = z.output<typeof Schema>;
